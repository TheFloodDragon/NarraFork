import { link, mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";
import {
	buildBundledPlugins,
	bundledPluginArchiveIdentity,
	renderBundledPluginModule,
} from "./build-bundled-plugins";

const ROOT = resolve(import.meta.dir, "..");

/** Compatibility shape for the retired catalog-only builtin materializer. Never scan old packages. */
export async function renderBuiltinPluginModule(_root = ROOT): Promise<string> {
	return `// GENERATED by scripts/generate-builtin-plugins.ts — do not edit.
// Quota ships only as an installable .nfplugin archive, not a second catalog-only package.
export interface EmbeddedBuiltinFile {
	path: string;
	content: string;
}
export interface EmbeddedBuiltinPackage {
	dir: string;
	pluginId: string;
	version: string;
	files: readonly EmbeddedBuiltinFile[];
}
export const embeddedBuiltinPlugins: readonly EmbeddedBuiltinPackage[] = [];
`;
}

/**
 * Shared by release and immutable local runtime builds. Build in an exclusive staging directory,
 * retain only a content-addressed archive, and return generated sources for in-memory interception.
 * No writes to server/generated or the shared plugin dist occur here; concurrent compilers can
 * safely keep using earlier archives while a new source revision is packaged.
 */
async function buildPluginModules(checkout: string): Promise<Map<string, string>> {
	const cache = join(checkout, ".narrafork", "bundled-plugin-build-assets");
	await mkdir(cache, { recursive: true });
	const staging = await mkdtemp(join(cache, "staging-"));
	try {
		const built = await buildBundledPlugins({
			root: checkout,
			outDir: staging,
			publishGenerated: false,
		});
		const asset = built.assets[0];
		if (built.assets.length !== 1 || !asset)
			throw new Error("Missing bundled Provider Quota archive");
		const archivePath = join(cache, `${asset.sha256}.nfplugin`);
		try {
			// The staged archive is complete and closed. Hard-link publication is atomic and exclusive.
			await link(asset.archivePath, archivePath);
		} catch (error) {
			if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error;
		}
		const stored = await bundledPluginArchiveIdentity(archivePath);
		if (stored.size !== asset.size || stored.sha256 !== asset.sha256) {
			throw new Error("Immutable bundled plugin build asset identity mismatch");
		}
		return new Map([
			["embedded-builtin-plugins.ts", await renderBuiltinPluginModule(checkout)],
			["embedded-bundled-plugins.ts", renderBundledPluginModule(asset, archivePath)],
		]);
	} finally {
		await rm(staging, { recursive: true, force: true });
	}
}

const frozenBuilds = new Map<string, Promise<Map<string, string>>>();

/** Freeze once per target checkout in this build process; callers receive their own map. */
export async function collectPluginBuildModules(root = ROOT): Promise<Map<string, string>> {
	const checkout = resolve(root);
	let frozen = frozenBuilds.get(checkout);
	if (!frozen) {
		frozen = buildPluginModules(checkout);
		frozenBuilds.set(checkout, frozen);
	}
	try {
		return new Map(await frozen);
	} catch (error) {
		if (frozenBuilds.get(checkout) === frozen) frozenBuilds.delete(checkout);
		throw error;
	}
}

if (import.meta.main) {
	const generated = join(ROOT, "server", "generated");
	await mkdir(generated, { recursive: true });
	for (const [name, body] of await collectPluginBuildModules(ROOT)) {
		const output = join(generated, name);
		await writeFile(output, body, "utf8");
		console.log(`Generated ${relative(process.cwd(), output)}`);
	}
}
